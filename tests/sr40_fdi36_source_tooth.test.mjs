import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url));
const text=p=>read(p).toString('utf8');
const gitBlobSha=b=>crypto.createHash('sha1').update(Buffer.concat([Buffer.from('blob '+b.length+'\0'),b])).digest('hex');
test('SR40 six browser/native FDI case identities and endodontic practical remain source aligned',()=>{
 const ids=['molar','endo','anterior','crown','surgery','perio'];
 const fdis=['16','36','11','26','48','46'];
 const app=text('native-godot/app.gd');
 const volume=text('native-godot/volume-cut.gd');
 const exporter=text('native-godot/export-content.mjs');
 const browser=text('app.js');
 assert.match(app,/\["molar",\s*"endo",\s*"anterior",\s*"crown",\s*"surgery",\s*"perio"\]/);
 assert.match(app,/\["16",\s*"36",\s*"11",\s*"26",\s*"48",\s*"46"\]/);
 assert.match(volume,/"endo":"36"/);
 assert.match(exporter,/\['molar','endo','anterior','crown','surgery','perio'\]/);
 assert.match(exporter,/\['16','36','11','26','48','46'\]/);
 const practical=browser.slice(browser.indexOf('function getPractical(caseData)'),browser.indexOf('\nclass PrepCanvas'));
 assert.match(practical,/if\(caseData\.id==='endo'\)/);
 assert.match(practical,/Arbeitslänge bestimmen/);
 assert.match(practical,/Spülung sicher durchführen/);
 assert.match(practical,/Wurzelkanalfüllung und koronaler Verschluss/);
 assert.deepEqual(ids,['molar','endo','anterior','crown','surgery','perio']);
 assert.deepEqual(fdis,['16','36','11','26','48','46']);
});
test('SR40 FDI36 surface source is byte-identical to pinned Dundee upstream commit and CC BY 4.0',()=>{
 const original=read('assets/dundee/mandibular_first_molar.glb');
 assert.equal(gitBlobSha(original),'73e9f3029d770c6b4052ebbaba708283de4c47fd');
 const notice=text('assets/dundee/README.md');
 assert.match(notice,/University of Dundee, School of Dentistry/);
 assert.match(notice,/Creative Commons Attribution \(CC BY 4\.0\)/);
 assert.match(notice,/4f0ffb651998a4641ddf45c7632ea236cc164fcb/);
 assert.match(notice,/mandibular_first_molar\.glb.*\(36\)/);
 assert.match(notice,/surface meshes only/);
 assert.match(notice,/not validated for diagnosis, endodontic planning/);
});
test('SR40 native FDI36 source mesh has a separate labelled fallback and stays separate from synthetic volume',()=>{
 const loader=text('native-godot/tooth36-reference.gd');
 const app=text('native-godot/app.gd');
 const build=text('native-godot/build-app.mjs');
 const smoke=text('native-godot/actual-app-smoke.gd');
 assert.match(loader,/KL_DUNDEE_FDI36_CC_BY_4_SURFACE_REFERENCE/);
 assert.match(loader,/KL_DUNDEE_FDI36_SURFACE_ASSET_MISSING_FALLBACK/);
 assert.match(loader,/internalTissuesProvided/);
 assert.match(loader,/clinicalAccuracyValidated/);
 assert.match(loader,/RAW_RESOLVER\.verified_path/);
 assert.match(app,/_view == "clinic" and _station_index == 4 and _case_index == 1/);
 assert.match(app,/Editable synthetic working volume remains separate/);
 assert.match(build,/expectedToothBlob/);
 assert.match(build,/decode-draco-tooth\.mjs/);
 assert.match(build,/nativeDundeeFDI36License:'CC-BY-4\.0'/);
 assert.match(smoke,/Actual source-verified Dundee FDI36 mesh did not load/);
 assert.match(smoke,/FDI36 missing-asset fallback was not clearly exposed/);
});
test('SR40 Draco converter verifies original blob identity and removes unsupported compression extension',()=>{
 const script=text('native-godot/decode-draco-tooth.mjs');
 assert.match(script,/KHR_draco_mesh_compression/);
 assert.match(script,/73e9f3029d770c6b4052ebbaba708283de4c47fd/);
 assert.match(script,/GetAttributeFloatForAllPoints/);
 assert.match(script,/GetFaceFromMesh/);
 assert.match(script,/texturePreserved:false/);
});
