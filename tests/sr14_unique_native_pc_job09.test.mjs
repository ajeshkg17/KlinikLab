import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {validateGodotJob,EXACT_SOURCE_SHA} from '../visual-qa/godot-job-core.mjs';
const root=path.resolve(import.meta.dirname,'..');
const get=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const NEW_SHA='ed3239c85a499205bf76b13395dc54c87b8ffe75';
const JOB='pc-godot-exported-20261101-cc0-job09-ed3239';
test('SR14: unique immutable exported-app queue is pinned to successful Windows artifact SHA; old job08 preserved',()=>{
 const current=get('visual-qa/jobs/godot-current.json');
 const previous=get('visual-qa/jobs/godot-job08-original.json');
 assert.equal(validateGodotJob(current).commit,NEW_SHA);
 assert.equal(current.jobId,JOB);
 assert.equal(current.schemaVersion,8);
 assert.equal(current.sceneMode,'native-exported-cc0');
 assert.equal(current.timeoutSec,180);
 assert.equal(current.capture,'native-exported-cc0-and-fdi36-two-pngs');
 assert.equal(current.graphics,'forward_plus-vulkan');
 assert.equal(current.backgroundContract,'private-winsta0-vulkan-autocapture-no-foreground');
 assert.equal(previous.schemaVersion,7);
 assert.equal(previous.commit,EXACT_SOURCE_SHA);
 assert.equal(previous.jobId,'pc-godot-clinic-20261101-job08');
 assert.notEqual(current.commit,previous.commit);
 assert.notEqual(current.jobId,previous.jobId);
 assert.throws(()=>validateGodotJob({...current,commit:previous.commit.slice(0,20)}));
 assert.throws(()=>validateGodotJob({...current,timeoutSec:420}));
});
test('SR14: job request cannot insert commands or use unknown external artifact',()=>{
 const current=get('visual-qa/jobs/godot-current.json');
 assert.throws(()=>validateGodotJob({...current,command:'powershell.exe'}));
 assert.throws(()=>validateGodotJob({...current,downloadUrl:'https://example.invalid/'}));
 assert.throws(()=>validateGodotJob({...current,suite:'source-only-prototype'}));
 const instructions=fs.readFileSync(path.join(root,'visual-qa/SR14_OWNER_PC_EXPORTED_APP_JOB09.md'),'utf8');
 assert(instructions.includes('13082771261'));
 assert(instructions.includes('41304091271'));
 assert(instructions.includes(NEW_SHA));
 assert(instructions.includes(JOB));
 assert(instructions.includes('EVIDENCE_INCOMPLETE'));
 assert(instructions.includes('NOT_ACCEPTED_PENDING_INDEPENDENT_PIXEL_REVIEW'));
});
